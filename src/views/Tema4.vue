        h2 4.2 Negociación

      p.mb-4 Cuando dos áreas sostienen posiciones incompatibles, el camino no es determinar quién tuvo razón, sino construir un acuerdo que ambas puedan cumplir. En la comunicación interna, eso significa establecer cómo van a operar en adelante: qué información se comparte, en qué plazo, por qué canal y con qué responsable.

